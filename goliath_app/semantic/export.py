"""Export semantic catalog JSON Schema and PostgreSQL composite row types."""

from __future__ import annotations

import argparse
import hashlib
import json
import sys
from pathlib import Path
from typing import Any, Dict, List, Optional, Sequence

from pydantic import BaseModel

from goliath_app.semantic.catalog import SEMANTIC_CATALOG, SEMANTIC_REQUESTS
from goliath_app.semantic.spec import SemanticEntitySpec, SemanticRequestSpec
from goliath_app.semantic.meta_bridge import (
    meta_class_catalog_type_name,
    meta_class_schema_id,
    meta_class_storage_relation,
)


def _canonical_bytes(payload: Any) -> bytes:
    return json.dumps(payload, sort_keys=True, separators=(",", ":")).encode("utf-8")


def content_hash_for(payload: Any) -> str:
    return hashlib.sha256(_canonical_bytes(payload)).hexdigest()


def _schema_id(entity: SemanticEntitySpec) -> str:
    if entity.meta_class_name:
        return meta_class_schema_id(entity.meta_class_name)
    return f"goliath.semantic/{entity.namespace}/{entity.code}/{entity.schema_version}"


def _request_schema_id(req: SemanticRequestSpec) -> str:
    return f"goliath.semantic/{req.namespace}/{req.request_code}/{req.version}"


def _pg_type_for_field(field_schema: dict[str, Any]) -> str:
    if "anyOf" in field_schema:
        for option in field_schema["anyOf"]:
            if option.get("type") != "null":
                return _pg_type_for_field(option)
    field_type = field_schema.get("type")
    if field_type == "integer":
        return "integer"
    if field_type == "boolean":
        return "boolean"
    if field_type == "number":
        return "double precision"
    if field_schema.get("format") == "date-time":
        return "timestamptz"
    return "text"


def _row_type_name(entity: SemanticEntitySpec) -> str:
    return f"{entity.namespace}_{entity.code}_row".replace(".", "_")


def export_row_types_sql(catalog: Sequence[SemanticEntitySpec]) -> str:
    lines = [
        "/*",
        "  Composite row types for semantic requests (generated by goliath-semantic-export).",
        "  Do not edit by hand; run goliath-semantic-export -o workflow_engine/sql_pg/portal_semantic_row_types.sql",
        "*/",
        "",
    ]
    for entity in catalog:
        if entity.meta_class_name:
            continue
        model_schema = entity.row_model.model_json_schema(mode="serialization")
        props = model_schema.get("properties", {})
        type_name = _row_type_name(entity)
        field_parts: List[str] = []
        for name in props:
            pg_t = _pg_type_for_field(props.get(name, {}))
            field_parts.append(f"  {name} {pg_t}")
        fields_sql = ",\n".join(field_parts)
        alter_lines = [
            f"ALTER TYPE portal.{type_name} ADD ATTRIBUTE IF NOT EXISTS {name} {_pg_type_for_field(props.get(name, {}))};"
            for name in props
        ]
        lines.extend(
            [
                "DO $$",
                "BEGIN",
                "  IF NOT EXISTS (",
                "    SELECT 1 FROM pg_type t",
                "    JOIN pg_namespace n ON n.oid = t.typnamespace",
                f"    WHERE n.nspname = 'portal' AND t.typname = '{type_name}'",
                "  ) THEN",
                f"    CREATE TYPE portal.{type_name} AS (",
                f"{fields_sql}",
                "    );",
                "  END IF;",
                "END $$;",
                *alter_lines,
                "",
            ]
        )
    return "\n".join(lines)


def _entity_by_code(code: str) -> SemanticEntitySpec:
    for entity in SEMANTIC_CATALOG:
        if entity.code == code:
            return entity
    raise KeyError(f"unknown entity code {code}")


def export_catalog_document() -> Dict[str, Any]:
    entities: Dict[str, Any] = {}
    for entity in SEMANTIC_CATALOG:
        if entity.meta_class_name:
            row_schema = {
                "$ref": meta_class_schema_id(entity.meta_class_name),
                "catalog_type": meta_class_catalog_type_name(entity.meta_class_name),
            }
            storage = entity.storage_relation or meta_class_storage_relation(
                entity.meta_class_name
            )
            schema_version = entity.schema_version
        else:
            row_schema = entity.row_model.model_json_schema(mode="serialization")
            storage = entity.storage_relation
            schema_version = entity.schema_version

        entity_hash = content_hash_for(
            {
                "namespace": entity.namespace,
                "code": entity.code,
                "schema_version": schema_version,
                "meta_class_id": entity.meta_class_id,
                "meta_class_name": entity.meta_class_name,
                "row_schema": row_schema,
                "attributes": [a.__dict__ for a in entity.attributes],
            }
        )
        entities[f"{entity.namespace}.{entity.code}"] = {
            "namespace": entity.namespace,
            "code": entity.code,
            "display_name": entity.display_name,
            "description": entity.description,
            "schema_id": _schema_id(entity),
            "schema_version": schema_version,
            "content_hash": entity_hash,
            "storage_relation": storage,
            "meta_class_id": entity.meta_class_id,
            "meta_class_name": entity.meta_class_name,
            "catalog_type_name": (
                meta_class_catalog_type_name(entity.meta_class_name)
                if entity.meta_class_name
                else None
            ),
            "row_type": f"portal.{_row_type_name(entity)}",
            "row_schema": row_schema,
            "attributes": [
                {
                    "code": a.code,
                    "column_name": a.column_name,
                    "json_type": a.json_type,
                    "role": a.role,
                    "filterable_ops": list(a.filterable_ops),
                }
                for a in entity.attributes
            ],
        }

    requests: Dict[str, Any] = {}
    for req in SEMANTIC_REQUESTS:
        entity = _entity_by_code(req.entity_code)
        params_schema = req.params_model.model_json_schema(mode="serialization")
        result_schema = req.result_row_model.model_json_schema(mode="serialization")
        filter_payload = (
            req.filter_template.model_dump(mode="json") if req.filter_template is not None else None
        )
        req_hash = content_hash_for(
            {
                "request_code": req.request_code,
                "version": req.version,
                "params_schema": params_schema,
                "result_schema": result_schema,
                "filter_template": filter_payload,
            }
        )
        requests[req.request_code] = {
            "request_code": req.request_code,
            "version": req.version,
            "namespace": req.namespace,
            "entity_code": req.entity_code,
            "target_kind": req.target_kind,
            "target_name": req.target_name,
            "row_type": f"portal.{_row_type_name(entity)}",
            "params_schema": params_schema,
            "result_schema": result_schema,
            "filter_template": filter_payload,
            "schema_id": _request_schema_id(req),
            "content_hash": req_hash,
            "required_permission": req.required_permission,
            "max_rows": req.max_rows,
            "base_namespace": req.base_namespace,
        }

    return {
        "entities": entities,
        "requests": requests,
        "row_types_sql": export_row_types_sql(SEMANTIC_CATALOG),
    }


def _check_mode(catalog_path: Path, row_types_path: Optional[Path]) -> int:
    with catalog_path.open(encoding="utf-8") as fh:
        committed = json.load(fh)
    live = export_catalog_document()
    if committed != {k: v for k, v in live.items() if k != "row_types_sql"}:
        print("semantic export drift: regenerate schemas/semantic/catalog.json", file=sys.stderr)
        return 1
    if row_types_path is not None:
        live_sql = live["row_types_sql"]
        if row_types_path.read_text(encoding="utf-8") != live_sql:
            print(
                "semantic export drift: regenerate portal_semantic_row_types.sql",
                file=sys.stderr,
            )
            return 1
    return 0


def main(argv: Optional[Sequence[str]] = None) -> int:
    parser = argparse.ArgumentParser(description="Export Goliath semantic catalog")
    parser.add_argument(
        "--check",
        metavar="PATH",
        help="Compare export to committed catalog.json",
    )
    parser.add_argument(
        "--row-types",
        metavar="PATH",
        help="Path to portal_semantic_row_types.sql for --check",
    )
    parser.add_argument("-o", "--output", metavar="PATH", help="Write row types SQL")
    parser.add_argument(
        "--catalog",
        metavar="PATH",
        help="Write catalog.json (entities + requests, without row_types_sql)",
    )
    args = parser.parse_args(list(argv) if argv is not None else None)

    if args.check:
        row_path = Path(args.row_types) if args.row_types else None
        return _check_mode(Path(args.check), row_path)

    document = export_catalog_document()
    if args.catalog:
        catalog_doc = {k: v for k, v in document.items() if k != "row_types_sql"}
        Path(args.catalog).write_text(
            json.dumps(catalog_doc, indent=2, sort_keys=True) + "\n",
            encoding="utf-8",
        )
    if args.output:
        Path(args.output).write_text(document["row_types_sql"], encoding="utf-8")
    elif not args.catalog:
        sys.stdout.write(json.dumps(document, indent=2, sort_keys=True) + "\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
