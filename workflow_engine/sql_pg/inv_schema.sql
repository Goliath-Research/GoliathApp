-- Domain-neutral inventory & purchasing module (optional; child apps extend via Meta / domain actions).
-- See docs/inventory-module.md for extension-owned inventory documentation.

CREATE SCHEMA IF NOT EXISTS inv;

CREATE TABLE IF NOT EXISTS inv.unit (
  unit_code text PRIMARY KEY,
  display_name text NOT NULL
);

INSERT INTO inv.unit (unit_code, display_name)
VALUES
  ('ea', 'Each'),
  ('kg', 'Kilogram'),
  ('g', 'Gram'),
  ('L', 'Liter'),
  ('m', 'Meter')
ON CONFLICT (unit_code) DO NOTHING;

CREATE TABLE IF NOT EXISTS inv.unit_conversion (
  organization_id integer NOT NULL,
  from_unit text NOT NULL REFERENCES inv.unit (unit_code),
  to_unit text NOT NULL REFERENCES inv.unit (unit_code),
  factor numeric(18, 8) NOT NULL CHECK (factor > 0),
  PRIMARY KEY (organization_id, from_unit, to_unit)
);

CREATE TABLE IF NOT EXISTS inv.item (
  item_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  organization_id integer NOT NULL,
  item_number text NOT NULL,
  description text NOT NULL DEFAULT '',
  base_unit text NOT NULL DEFAULT 'ea' REFERENCES inv.unit (unit_code),
  category text NULL,
  make_or_buy text NOT NULL DEFAULT 'buy'
    CHECK (make_or_buy IN ('make', 'buy', 'both')),
  lot_controlled boolean NOT NULL DEFAULT false,
  serial_controlled boolean NOT NULL DEFAULT false,
  shelf_life_days integer NULL,
  costing_method text NOT NULL DEFAULT 'moving_average'
    CHECK (costing_method IN ('moving_average', 'standard')),
  standard_unit_cost numeric(18, 6) NULL,
  avg_unit_cost numeric(18, 6) NOT NULL DEFAULT 0,
  active boolean NOT NULL DEFAULT true,
  created_at_utc timestamptz NOT NULL DEFAULT (now() AT TIME ZONE 'utc'),
  CONSTRAINT uq_inv_item_org_number UNIQUE (organization_id, item_number)
);

CREATE INDEX IF NOT EXISTS ix_inv_item_organization
  ON inv.item (organization_id);

CREATE TABLE IF NOT EXISTS inv.supplier (
  supplier_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  organization_id integer NOT NULL,
  supplier_code text NOT NULL,
  name text NOT NULL,
  active boolean NOT NULL DEFAULT true,
  CONSTRAINT uq_inv_supplier_org_code UNIQUE (organization_id, supplier_code)
);

CREATE INDEX IF NOT EXISTS ix_inv_supplier_organization
  ON inv.supplier (organization_id);

-- Approved Supplier List (ASL): item-specific or supplier-wide when item_id IS NULL.
CREATE TABLE IF NOT EXISTS inv.approved_supplier (
  approved_supplier_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  organization_id integer NOT NULL,
  supplier_id integer NOT NULL REFERENCES inv.supplier (supplier_id) ON DELETE CASCADE,
  item_id integer NULL REFERENCES inv.item (item_id) ON DELETE CASCADE,
  approved_from date NOT NULL DEFAULT CURRENT_DATE,
  approved_to date NULL
);

CREATE UNIQUE INDEX IF NOT EXISTS uq_inv_approved_supplier_item
  ON inv.approved_supplier (organization_id, supplier_id, item_id)
  WHERE item_id IS NOT NULL;

CREATE UNIQUE INDEX IF NOT EXISTS uq_inv_approved_supplier_supplier_wide
  ON inv.approved_supplier (organization_id, supplier_id)
  WHERE item_id IS NULL;

CREATE TABLE IF NOT EXISTS inv.supplier_item (
  supplier_item_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  organization_id integer NOT NULL,
  supplier_id integer NOT NULL REFERENCES inv.supplier (supplier_id),
  item_id integer NOT NULL REFERENCES inv.item (item_id),
  supplier_part_number text NOT NULL,
  description text NOT NULL DEFAULT '',
  manufacturer_part_number text NULL,
  pack_size numeric(18, 6) NOT NULL DEFAULT 1 CHECK (pack_size > 0),
  pack_unit text NOT NULL DEFAULT 'ea' REFERENCES inv.unit (unit_code),
  lead_time_days integer NULL,
  minimum_order_qty numeric(18, 6) NULL,
  preferred boolean NOT NULL DEFAULT false,
  active boolean NOT NULL DEFAULT true,
  CONSTRAINT uq_inv_supplier_item UNIQUE (organization_id, supplier_id, supplier_part_number)
);

CREATE INDEX IF NOT EXISTS ix_inv_supplier_item_item
  ON inv.supplier_item (organization_id, item_id);

CREATE TABLE IF NOT EXISTS inv.supplier_item_price_break (
  price_break_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  supplier_item_id integer NOT NULL REFERENCES inv.supplier_item (supplier_item_id) ON DELETE CASCADE,
  min_qty numeric(18, 6) NOT NULL CHECK (min_qty > 0),
  unit_price numeric(18, 6) NOT NULL CHECK (unit_price >= 0),
  currency_code char(3) NOT NULL DEFAULT 'USD',
  effective_from date NOT NULL DEFAULT CURRENT_DATE,
  effective_to date NULL
);

CREATE INDEX IF NOT EXISTS ix_inv_price_break_supplier_item
  ON inv.supplier_item_price_break (supplier_item_id, effective_from DESC);

CREATE TABLE IF NOT EXISTS inv.item_alternate (
  organization_id integer NOT NULL,
  item_id integer NOT NULL REFERENCES inv.item (item_id) ON DELETE CASCADE,
  alternate_item_id integer NOT NULL REFERENCES inv.item (item_id) ON DELETE CASCADE,
  PRIMARY KEY (organization_id, item_id, alternate_item_id),
  CHECK (item_id <> alternate_item_id)
);

CREATE TABLE IF NOT EXISTS inv.customer_item_ref (
  organization_id integer NOT NULL,
  item_id integer NOT NULL REFERENCES inv.item (item_id) ON DELETE CASCADE,
  customer_ref text NOT NULL,
  customer_part_number text NOT NULL,
  PRIMARY KEY (organization_id, item_id, customer_ref, customer_part_number)
);

CREATE TABLE IF NOT EXISTS inv.location (
  location_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  organization_id integer NOT NULL,
  location_code text NOT NULL,
  name text NOT NULL,
  active boolean NOT NULL DEFAULT true,
  CONSTRAINT uq_inv_location_org_code UNIQUE (organization_id, location_code)
);

CREATE TABLE IF NOT EXISTS inv.bin (
  bin_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  location_id integer NOT NULL REFERENCES inv.location (location_id) ON DELETE CASCADE,
  bin_code text NOT NULL,
  active boolean NOT NULL DEFAULT true,
  CONSTRAINT uq_inv_bin_location_code UNIQUE (location_id, bin_code)
);

CREATE TABLE IF NOT EXISTS inv.stock_lot (
  stock_lot_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  organization_id integer NOT NULL,
  item_id integer NOT NULL REFERENCES inv.item (item_id),
  bin_id integer NOT NULL REFERENCES inv.bin (bin_id),
  lot_number text NULL,
  serial_number text NULL,
  qty_on_hand numeric(18, 6) NOT NULL DEFAULT 0 CHECK (qty_on_hand >= 0),
  unit_cost numeric(18, 6) NOT NULL DEFAULT 0,
  received_at_utc timestamptz NOT NULL DEFAULT (now() AT TIME ZONE 'utc'),
  expires_on date NULL
);

CREATE INDEX IF NOT EXISTS ix_inv_stock_lot_item
  ON inv.stock_lot (organization_id, item_id);

CREATE TABLE IF NOT EXISTS inv.stock_move (
  stock_move_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  organization_id integer NOT NULL,
  item_id integer NOT NULL REFERENCES inv.item (item_id),
  stock_lot_id integer NULL REFERENCES inv.stock_lot (stock_lot_id),
  move_type text NOT NULL
    CHECK (move_type IN ('receive', 'adjust', 'issue', 'cycle_count', 'reserve')),
  qty_delta numeric(18, 6) NOT NULL,
  unit_cost numeric(18, 6) NOT NULL DEFAULT 0,
  ref_type text NULL,
  ref_id text NULL,
  reason_code text NULL,
  created_at_utc timestamptz NOT NULL DEFAULT (now() AT TIME ZONE 'utc'),
  created_by_user_id integer NULL
);

CREATE INDEX IF NOT EXISTS ix_inv_stock_move_org_item
  ON inv.stock_move (organization_id, item_id, created_at_utc DESC);

CREATE TABLE IF NOT EXISTS inv.stock_reservation (
  reservation_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  organization_id integer NOT NULL,
  item_id integer NOT NULL REFERENCES inv.item (item_id),
  stock_lot_id integer NULL REFERENCES inv.stock_lot (stock_lot_id),
  qty_reserved numeric(18, 6) NOT NULL CHECK (qty_reserved > 0),
  ref_type text NOT NULL,
  ref_id text NOT NULL,
  status text NOT NULL DEFAULT 'open'
    CHECK (status IN ('open', 'fulfilled', 'cancelled')),
  created_at_utc timestamptz NOT NULL DEFAULT (now() AT TIME ZONE 'utc')
);

CREATE TABLE IF NOT EXISTS inv.stock_adjustment (
  adjustment_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  organization_id integer NOT NULL,
  item_id integer NOT NULL REFERENCES inv.item (item_id),
  stock_lot_id integer NULL REFERENCES inv.stock_lot (stock_lot_id),
  qty_delta numeric(18, 6) NOT NULL CHECK (qty_delta <> 0),
  reason_code text NOT NULL,
  created_at_utc timestamptz NOT NULL DEFAULT (now() AT TIME ZONE 'utc'),
  created_by_user_id integer NULL
);

CREATE TABLE IF NOT EXISTS inv.cycle_count (
  cycle_count_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  organization_id integer NOT NULL,
  location_id integer NOT NULL REFERENCES inv.location (location_id),
  status text NOT NULL DEFAULT 'open'
    CHECK (status IN ('open', 'posted', 'cancelled')),
  created_at_utc timestamptz NOT NULL DEFAULT (now() AT TIME ZONE 'utc'),
  posted_at_utc timestamptz NULL
);

CREATE TABLE IF NOT EXISTS inv.cycle_count_line (
  cycle_count_line_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  cycle_count_id integer NOT NULL REFERENCES inv.cycle_count (cycle_count_id) ON DELETE CASCADE,
  bin_id integer NOT NULL REFERENCES inv.bin (bin_id),
  item_id integer NOT NULL REFERENCES inv.item (item_id),
  stock_lot_id integer NULL REFERENCES inv.stock_lot (stock_lot_id),
  expected_qty numeric(18, 6) NOT NULL DEFAULT 0,
  counted_qty numeric(18, 6) NULL,
  variance_qty numeric(18, 6) NULL
);

CREATE TABLE IF NOT EXISTS inv.reorder_point (
  reorder_point_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  organization_id integer NOT NULL,
  item_id integer NOT NULL REFERENCES inv.item (item_id) ON DELETE CASCADE,
  location_id integer NULL REFERENCES inv.location (location_id) ON DELETE CASCADE,
  min_qty numeric(18, 6) NOT NULL CHECK (min_qty >= 0),
  max_qty numeric(18, 6) NULL,
  reorder_qty numeric(18, 6) NOT NULL CHECK (reorder_qty > 0)
);

DROP INDEX IF EXISTS inv.uq_inv_reorder_point_org_item_location;
CREATE UNIQUE INDEX uq_inv_reorder_point_org_item_location
  ON inv.reorder_point (organization_id, item_id, location_id)
  NULLS NOT DISTINCT;

CREATE TABLE IF NOT EXISTS inv.purchase_order (
  purchase_order_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  organization_id integer NOT NULL,
  supplier_id integer NOT NULL REFERENCES inv.supplier (supplier_id),
  po_number text NOT NULL,
  status text NOT NULL DEFAULT 'draft'
    CHECK (status IN ('draft', 'submitted', 'partial', 'closed', 'cancelled')),
  ordered_at_utc timestamptz NULL,
  created_at_utc timestamptz NOT NULL DEFAULT (now() AT TIME ZONE 'utc'),
  CONSTRAINT uq_inv_po_org_number UNIQUE (organization_id, po_number)
);

CREATE TABLE IF NOT EXISTS inv.purchase_order_line (
  po_line_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  purchase_order_id integer NOT NULL REFERENCES inv.purchase_order (purchase_order_id) ON DELETE CASCADE,
  line_number integer NOT NULL,
  item_id integer NOT NULL REFERENCES inv.item (item_id),
  supplier_item_id integer NULL REFERENCES inv.supplier_item (supplier_item_id),
  qty_ordered numeric(18, 6) NOT NULL CHECK (qty_ordered > 0),
  unit_price numeric(18, 6) NOT NULL CHECK (unit_price >= 0),
  qty_received numeric(18, 6) NOT NULL DEFAULT 0 CHECK (qty_received >= 0),
  CONSTRAINT uq_inv_po_line UNIQUE (purchase_order_id, line_number)
);

CREATE TABLE IF NOT EXISTS inv.receipt (
  receipt_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  organization_id integer NOT NULL,
  po_line_id integer NOT NULL REFERENCES inv.purchase_order_line (po_line_id),
  stock_lot_id integer NOT NULL REFERENCES inv.stock_lot (stock_lot_id),
  qty_received numeric(18, 6) NOT NULL CHECK (qty_received > 0),
  received_at_utc timestamptz NOT NULL DEFAULT (now() AT TIME ZONE 'utc'),
  received_by_user_id integer NULL
);

CREATE TABLE IF NOT EXISTS inv.item_cost_snapshot (
  item_id integer NOT NULL REFERENCES inv.item (item_id) ON DELETE CASCADE,
  captured_at_utc timestamptz NOT NULL DEFAULT (now() AT TIME ZONE 'utc'),
  avg_unit_cost numeric(18, 6) NOT NULL,
  qty_on_hand numeric(18, 6) NOT NULL,
  PRIMARY KEY (item_id, captured_at_utc)
);

