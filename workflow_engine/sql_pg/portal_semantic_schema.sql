/*
  Portal semantic registry (A1).
  Prerequisites: portal shell, portal_organization_schema, wf_semantic_action_catalog.sql
*/

CREATE SCHEMA IF NOT EXISTS portal;

-- Application SQLSTATE codes for the semantic runner.
CREATE OR REPLACE FUNCTION portal.fn_semantic_raise(p_code text, p_message text)
RETURNS void
LANGUAGE plpgsql
AS $$
BEGIN
  RAISE EXCEPTION '%', p_message USING ERRCODE = p_code;
END;
$$;

CREATE TABLE IF NOT EXISTS portal.semantic_namespace (
  code text PRIMARY KEY,
  display_name text NOT NULL,
  owner_app text NOT NULL DEFAULT 'goliath_app',
  created_at_utc timestamptz NOT NULL DEFAULT (now() AT TIME ZONE 'utc')
);

CREATE TABLE IF NOT EXISTS portal.semantic_entity (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  namespace text NOT NULL REFERENCES portal.semantic_namespace (code),
  code text NOT NULL,
  display_name text NOT NULL,
  description text NOT NULL DEFAULT '',
  meta_class_id integer NULL,
  storage_relation text NULL,
  schema_id text NOT NULL,
  schema_version text NOT NULL DEFAULT '1',
  content_hash text NOT NULL DEFAULT '',
  created_at_utc timestamptz NOT NULL DEFAULT (now() AT TIME ZONE 'utc'),
  CONSTRAINT uq_semantic_entity_ns_code UNIQUE (namespace, code)
);

CREATE INDEX IF NOT EXISTS ix_semantic_entity_namespace
  ON portal.semantic_entity (namespace);

CREATE TABLE IF NOT EXISTS portal.semantic_attribute (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  entity_id integer NOT NULL REFERENCES portal.semantic_entity (id) ON DELETE CASCADE,
  code text NOT NULL,
  column_name text NOT NULL,
  json_type text NOT NULL CHECK (json_type IN ('string', 'integer', 'number', 'boolean')),
  role text NOT NULL CHECK (role IN ('list', 'detail', 'filter', 'key')),
  filterable_ops text[] NOT NULL DEFAULT '{}',
  created_at_utc timestamptz NOT NULL DEFAULT (now() AT TIME ZONE 'utc'),
  CONSTRAINT uq_semantic_attribute_entity_code UNIQUE (entity_id, code)
);

CREATE INDEX IF NOT EXISTS ix_semantic_attribute_entity
  ON portal.semantic_attribute (entity_id);

CREATE TABLE IF NOT EXISTS portal.semantic_request (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  request_code text NOT NULL,
  version text NOT NULL DEFAULT '1',
  namespace text NOT NULL REFERENCES portal.semantic_namespace (code),
  base_namespace text NULL,
  entity_id integer NOT NULL REFERENCES portal.semantic_entity (id),
  target_kind text NOT NULL CHECK (target_kind IN ('view', 'function', 'template')),
  target_name text NOT NULL,
  row_type regtype NOT NULL,
  params_schema jsonb NOT NULL DEFAULT '{}'::jsonb,
  result_schema jsonb NOT NULL DEFAULT '{}'::jsonb,
  filter_template jsonb NULL,
  content_hash text NOT NULL DEFAULT '',
  required_permission text NULL,
  max_rows integer NOT NULL DEFAULT 500,
  created_at_utc timestamptz NOT NULL DEFAULT (now() AT TIME ZONE 'utc'),
  CONSTRAINT uq_semantic_request_code_version UNIQUE (request_code, version)
);

CREATE INDEX IF NOT EXISTS ix_semantic_request_entity
  ON portal.semantic_request (entity_id);

CREATE TABLE IF NOT EXISTS portal.semantic_action_binding (
  workflow_action_id bigint NOT NULL REFERENCES wf.workflow_action (id) ON DELETE CASCADE,
  entity_id integer NOT NULL REFERENCES portal.semantic_entity (id) ON DELETE CASCADE,
  created_at_utc timestamptz NOT NULL DEFAULT (now() AT TIME ZONE 'utc'),
  PRIMARY KEY (workflow_action_id, entity_id)
);

CREATE TABLE IF NOT EXISTS portal.semantic_nav_binding (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  entity_id integer NULL REFERENCES portal.semantic_entity (id) ON DELETE CASCADE,
  request_id integer NULL REFERENCES portal.semantic_request (id) ON DELETE CASCADE,
  nav_tree_id integer NOT NULL,
  permission_code text NULL,
  created_at_utc timestamptz NOT NULL DEFAULT (now() AT TIME ZONE 'utc'),
  CONSTRAINT ck_semantic_nav_binding_target CHECK (
    entity_id IS NOT NULL OR request_id IS NOT NULL
  )
);

ALTER TABLE wf.workflow_action
  ADD COLUMN IF NOT EXISTS semantic_entity_id integer NULL;

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint WHERE conname = 'fk_wf_action_semantic_entity'
  ) THEN
    ALTER TABLE wf.workflow_action
      ADD CONSTRAINT fk_wf_action_semantic_entity
      FOREIGN KEY (semantic_entity_id)
      REFERENCES portal.semantic_entity (id)
      ON DELETE SET NULL;
  END IF;
END $$;

INSERT INTO portal.semantic_namespace (code, display_name, owner_app)
VALUES
  ('engine', 'Workflow engine', 'goliath_app'),
  ('core', 'Goliath platform core', 'goliath_app')
ON CONFLICT (code) DO UPDATE
  SET display_name = EXCLUDED.display_name,
      owner_app = EXCLUDED.owner_app;
