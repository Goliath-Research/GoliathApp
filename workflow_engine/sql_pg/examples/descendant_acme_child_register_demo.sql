-- Example ONLY: neutral "acme_child" extension pattern for adopters (not run by apply_schema.sh).
-- Prerequisites: full apply_schema.sh has been executed; platform seeds are optional but typical.
--
-- This script demonstrates INSERT + CALL patterns for descendant-owned catalog rows.
-- Replace connection secrets with your vault / env; never commit passwords.
--
-- Run (superuser or migration owner), non-interactive:
--   psql -v ON_ERROR_STOP=1 "postgresql://USER:PASSWORD@HOST:5432/DBNAME?sslmode=require" -f descendant_acme_child_register_demo.sql
--
-- Idempotent: uses ON CONFLICT / register procedures that upsert.

BEGIN;

-- 1) Namespace row (owner_app labels the producing app; not a Python import).
INSERT INTO portal.semantic_namespace (code, display_name, owner_app)
VALUES ('acme_child', 'AcmeChild (demo namespace)', 'descendant_app')
ON CONFLICT (code) DO UPDATE
  SET display_name = EXCLUDED.display_name,
      owner_app = EXCLUDED.owner_app;

-- 2) Semantic entity (storage_relation targets a real table or view you own in a later migration).
CALL portal.sp_semantic_register_entity(
  'acme_child',
  'demo_part',
  'Demo part',
  'Synthetic parts catalog row for integration testing',
  'goliath.semantic/acme_child/demo_part/1',
  '1',
  'sha256:demo_content_hash_placeholder',
  'acme_child.part',  -- fictional table name; create the table in your app migration before production
  NULL
);

-- Resolve entity id for attributes (register procedures do not return it).
DO $$
DECLARE
  v_entity_id int;
BEGIN
  SELECT id INTO v_entity_id
  FROM portal.semantic_entity
  WHERE namespace = 'acme_child' AND code = 'demo_part';

  IF v_entity_id IS NULL THEN
    RAISE EXCEPTION 'acme_child.demo_part entity not found after register';
  END IF;

  CALL portal.sp_semantic_register_attribute(
    v_entity_id, 'part_id', 'part_id', 'integer', 'key', '{}'::text[]
  );
  CALL portal.sp_semantic_register_attribute(
    v_entity_id, 'sku', 'sku', 'string', 'list', '{}'::text[]
  );
END $$;

-- 3) NavTree node (caption shown in portal shell). Link Role2Node via portal RBAC APIs separately.
-- p_seq is smallint; use explicit casts so overload resolution matches portal.sp_nav_register_node.
SELECT portal.sp_nav_register_node(
  NULL::integer,
  'AcmeChild Demo',
  90::smallint,
  NULL::integer,
  '/acme-child-demo',
  '0090'
);

-- 4) Operational note: semantic *requests* require a matching composite row type in schema portal
-- (see portal_semantic_row_types.sql generated by goliath-semantic-export). Register with
-- portal.sp_semantic_register_request(...) after that type exists. This demo stops at entity + nav.

COMMIT;
