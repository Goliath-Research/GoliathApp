/*
  Idempotent migration: RBAC + Onboarding rows -> Meta security objects.
  Preserves legacy numeric ids on Meta.Objs where possible (GENERATED BY DEFAULT AS IDENTITY).
*/

CREATE TABLE IF NOT EXISTS portal.security_grant_cache (
  grant_obj_id integer NOT NULL PRIMARY KEY,
  user_id integer NOT NULL,
  role_id integer NOT NULL,
  scope_id integer NOT NULL,
  active boolean NOT NULL,
  revoked_at_utc timestamptz,
  bypass_scope boolean NOT NULL DEFAULT false
);

CREATE INDEX IF NOT EXISTS "IX_portal_security_grant_cache_user_scope"
  ON portal.security_grant_cache (user_id, scope_id)
  WHERE active AND revoked_at_utc IS NULL;

CREATE OR REPLACE FUNCTION portal.sp_security_meta_upsert_map(
  p_kind text,
  p_legacy_id bigint,
  p_obj_id int
)
RETURNS void
LANGUAGE sql
SECURITY DEFINER
SET search_path = portal, pg_temp
AS $$
  INSERT INTO portal.security_meta_legacy_map (legacy_kind, legacy_id, meta_obj_id)
  VALUES (lower(btrim(p_kind)), p_legacy_id, p_obj_id)
  ON CONFLICT (legacy_kind, legacy_id) DO UPDATE
    SET meta_obj_id = EXCLUDED.meta_obj_id;
$$;

